const esc = value => String(value).replace(/[&<>"']/g, char => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[char]));
const categoryTargets = { ai: "ai-projects", live: "live-projects", animation: "animation-projects" };
let projectById = {};

function cardMarkup(project, number) {
  projectById[project.id] = project;
  const poster = `assets/projects/${project.poster}`;
  return `<article class="work-item" style="--card-index:${number}">
    <button class="work-media project-open" type="button" data-project="${esc(project.id)}" aria-label="打开${esc(project.title)}的项目说明和视频">
      <img src="${esc(poster)}" alt="${esc(project.title)}项目画面" loading="lazy">
      <span class="media-topline"><span>${esc(project.label)}</span><span>${esc(project.year)}</span></span>
      <span class="media-play" aria-hidden="true">▶</span>
      <span class="media-bottom"><strong>${esc(project.title)}</strong><span>查看视频 / 项目说明 ↗</span></span>
    </button>
    <div class="work-copy">
      <p class="project-count">PROJECT ${String(number).padStart(2, "0")} <span>· ${esc(project.english)}</span></p>
      <h3>${esc(project.title)}</h3>
      <div class="thought-block"><span class="thought-label">创意思路</span><p>${esc(project.idea)}</p></div>
      <div class="contribution"><span>我的参与</span><p>${esc(project.role)}</p></div>
    </div>
  </article>`;
}

let n = 1;
for (const [group, targetId] of Object.entries(categoryTargets)) {
  document.getElementById(targetId).innerHTML = projects[group].map(project => cardMarkup(project, n++)).join("");
}

const dialog = document.querySelector(".project-dialog");
const dialogVideo = dialog.querySelector(".dialog-video");
const dialogEmbed = dialog.querySelector(".dialog-embed");
const dialogPlaceholder = dialog.querySelector(".dialog-placeholder");
const dialogPoster = dialog.querySelector(".dialog-poster");
document.querySelectorAll(".project-open").forEach(button => button.addEventListener("click", () => {
  const project = projectById[button.dataset.project];
  document.querySelector("#dialog-title").textContent = project.title;
  document.querySelector(".dialog-copy").textContent = project.idea;
  document.querySelector(".dialog-meta").textContent = `${project.label} / ${project.year} / ${project.role}`;
  dialogPoster.src = `assets/projects/${project.poster}`;
  dialogPoster.alt = `${project.title}项目画面`;
  dialogVideo.pause();
  dialogVideo.removeAttribute("src");
  dialogVideo.hidden = true;
  dialogEmbed.removeAttribute("src");
  dialogEmbed.hidden = true;
  if (project.video) {
    dialogVideo.src = project.video;
    dialogVideo.hidden = false;
    dialogPlaceholder.hidden = true;
  } else if (project.embed) {
    dialogEmbed.src = project.embed;
    dialogEmbed.hidden = false;
    dialogPlaceholder.hidden = true;
  } else {
    dialogPlaceholder.hidden = false;
  }
  dialog.showModal();
}));

function stopMedia() {
  dialogVideo.pause();
  dialogEmbed.removeAttribute("src");
}
document.querySelector(".dialog-close").addEventListener("click", () => dialog.close());
dialog.addEventListener("close", stopMedia);
dialog.addEventListener("click", event => { if (event.target === dialog) dialog.close(); });
